if __name__ == "__main__":
    out = []
    for n, (hx, hy, art) in Z.items():
        rows = [r for r in art.strip("\n").split("\n")]
        assert len(rows) == 16 and all(len(r) == 16 for r in rows), n
        a = []; x = []
        for r in rows:
            av = sum((1 << (15 - i)) for i, c in enumerate(r) if c == '.')
            xv = sum((1 << (15 - i)) for i, c in enumerate(r) if c == 'o')
            a += [av >> 8, av & 255]; x += [xv >> 8, xv & 255]
        out.append((n, hx, hy, a + x))
    print("static const BYTE zbild[4][66] = {   /* CUR_WAIT, CUR_TEXT, CUR_CROSS, CUR_HAND: Hotspot x, y, UND, XOR */")
    for n, hx, hy, b in out:
        print("    { %d, %d, " % (hx, hy) + ",".join("0x%02X" % v for v in b) + " },   /* %s */" % n)
    print("};")
